    o.write('// GERADO AUTOMATICAMENTE por gerar_glossario.py — não editar à mão.\n#import "/modelo/estilo.typ": *\n\n')
    o.write('#{\n  set text(size: 8.8pt)\n  tabela(\n    colunas: (1.2fr, 1.2fr, auto),\n    cabecalho: ([Português], [Inglês], [Ver]),\n')
    for pt, en, rot in G:
        ref = f'@{rot}' if rot else '—'
        o.write(f'    [{pt}], [_{en}_], [{ref}],\n')
    o.write('  )\n}\n')
    # Inglês → português
    o.write('\n== Índice inglês–português <sec-ap-glossario-en>\n\n#{\n  set text(size: 8.8pt)\n  tabela(\n    colunas: (1fr, 1fr),\n    cabecalho: ([Inglês], [Português]),\n')
    pares = []
    for pt, en, rot in G:
        for e in en.split(';'):
            pares.append((e.strip(), pt))
    pares.sort(key=lambda x: chave(x[0]))
    for en, pt in pares:
        o.write(f'    [_{en}_], [{pt}],\n')
    o.write('  )\n}\n')
